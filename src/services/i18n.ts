export function getTranslation(lang: UiLanguage, key: string, fallback?: string): string {
  const dict = translations[lang];
  if (dict && dict[key]) return dict[key];
  if (translations.cs && translations.cs[key]) return translations.cs[key];
  if (translations.en && translations.en[key]) return translations.en[key];
  return fallback || key;
}
